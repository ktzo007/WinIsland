/** Tombol ikon; stopPropagation supaya tidak memicu klik milik kapsul. */
export function IconButton({ name, size = 16, onClick, label, className = "", disabled, active, onMouseDown }) {
  return (
    <button
      type="button"
      title={label}
      aria-label={label}
      disabled={disabled}
      data-active={active ? "1" : undefined}
      onMouseDown={onMouseDown}
      onClick={(e) => {
        e.stopPropagation();
        onClick?.(e);
      }}
      className={`ibtn ${className}`}
    >
      <Icon name={name} size={size} />
    </button>
  );
}
